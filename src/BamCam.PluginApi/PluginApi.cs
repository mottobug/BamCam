using BamCam.Core.Cam;
using BamCam.Core.Model;

namespace BamCam.Plugins;

/// <summary>
/// Entry point of a plugin. BamCam creates every public, non-abstract class implementing this interface (with a
/// parameterless constructor) in an approved plugin assembly and calls <see cref="Initialize"/> once at start-up.
/// Name, vendor and version shown to the user come from the assembly attributes
/// (AssemblyTitle or AssemblyProduct, AssemblyCompany, AssemblyInformationalVersion / AssemblyVersion).
/// </summary>
public interface IBamCamPlugin
{
    /// <summary>Registers the plugin's commands and machining operations.</summary>
    void Initialize(IPluginHost host);
}

/// <summary>Services BamCam offers to a plugin while it initializes.</summary>
public interface IPluginHost
{
    /// <summary>Version of the running BamCam.</summary>
    Version HostVersion { get; }

    /// <summary>Active user interface language ("en", "de", ...), for the plugin's own texts.</summary>
    string Language { get; }

    /// <summary>Adds a menu command.</summary>
    void AddCommand(PluginCommand command);

    /// <summary>
    /// Adds a machining operation type. <typeparamref name="TOp"/> derives from <see cref="MachineOp"/> (or
    /// <see cref="DepthOp"/> for depth levels) and declares its parameters as <c>[Param]</c> properties of type
    /// <c>CamParam&lt;T&gt;</c>; they appear in the property grid and are saved in drawings. Its
    /// <see cref="MachineOp.XmlName"/> must be unique (e.g. prefixed with the vendor) – it is the xsi:type of the
    /// operation in .cb files. The operation appears in the Machining menu and is generated by
    /// <paramref name="generator"/>.
    /// </summary>
    void AddOperation<TOp>(Action<ToolpathContext, TOp, Toolpath> generator) where TOp : MachineOp, new();

    /// <summary>Writes a line to BamCam's message window.</summary>
    void Log(string message);
}

/// <summary>A menu command of a plugin.</summary>
public sealed class PluginCommand
{
    /// <summary>Menu entry text; an underscore marks the access key ("_Gear...").</summary>
    public required string Header { get; init; }

    /// <summary>Top-level menu the command is added to: "Plugins" (default), "Draw", "Edit" or "Machining".</summary>
    public string Menu { get; init; } = "Plugins";

    /// <summary>Optional tooltip.</summary>
    public string? Description { get; init; }

    /// <summary>When true the command is only run with selected drawing objects (otherwise BamCam asks to select some).</summary>
    public bool RequiresSelection { get; init; }

    /// <summary>The action. Changes to the drawing must go through <see cref="ICommandContext.Change"/> to be undoable.</summary>
    public required Func<ICommandContext, Task> Execute { get; init; }
}

/// <summary>What a running command can see and do.</summary>
public interface ICommandContext
{
    /// <summary>The open drawing.</summary>
    CadDocument Document { get; }

    /// <summary>Selected drawing objects.</summary>
    IReadOnlyList<Entity> Selection { get; }

    /// <summary>Runs <paramref name="change"/> as one undoable step named <paramref name="description"/> and refreshes the view.</summary>
    void Change(string description, Action change);

    /// <summary>Adds objects to the active layer as one undoable step and selects them.</summary>
    void AddEntities(string description, IEnumerable<Entity> entities);

    /// <summary>Replaces the selection.</summary>
    void Select(IEnumerable<Entity> entities);

    /// <summary>Writes a line to the message window.</summary>
    void Log(string message);

    /// <summary>Asks for a number; null when cancelled.</summary>
    Task<double?> AskNumber(string title, string label, double defaultValue);

    /// <summary>Asks for a text; null when cancelled.</summary>
    Task<string?> AskText(string title, string label, string defaultValue = "");
}
