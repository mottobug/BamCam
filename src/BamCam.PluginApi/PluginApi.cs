using BamCam.Core.Cam;
using BamCam.Core.Geometry;
using BamCam.Core.Model;

namespace BamCam.Plugins;

/// <summary>
/// Entry point of a plugin. BamCam creates every public, non-abstract class implementing this interface (with a
/// parameterless constructor) in an approved plugin assembly and calls <see cref="Initialize"/> once at start-up.
/// Name, vendor and version shown to the user come from the assembly attributes
/// (AssemblyTitle or AssemblyProduct, AssemblyCompany, AssemblyInformationalVersion / AssemblyVersion).
/// </summary>
public interface IBamCamPlugin
{
    /// <summary>Registers the plugin's commands and machining operations.</summary>
    void Initialize(IPluginHost host);
}

/// <summary>Services BamCam offers to a plugin while it initializes.</summary>
public interface IPluginHost
{
    /// <summary>Version of the running BamCam.</summary>
    Version HostVersion { get; }

    /// <summary>Active user interface language ("en", "de", ...), for the plugin's own texts.</summary>
    string Language { get; }

    /// <summary>Adds a menu command.</summary>
    void AddCommand(PluginCommand command);

    /// <summary>
    /// Adds a machining operation type. <typeparamref name="TOp"/> derives from <see cref="MachineOp"/> (or
    /// <see cref="DepthOp"/> for depth levels) and declares its parameters as <c>[Param]</c> properties of type
    /// <c>CamParam&lt;T&gt;</c>; they appear in the property grid and are saved in drawings. Its
    /// <see cref="MachineOp.XmlName"/> must be unique (e.g. prefixed with the vendor) – it is the xsi:type of the
    /// operation in .cb files. The operation appears in the Machining menu and is generated by
    /// <paramref name="generator"/>.
    /// </summary>
    void AddOperation<TOp>(Action<ToolpathContext, TOp, Toolpath> generator) where TOp : MachineOp, new();

    /// <summary>Writes a line to BamCam's message window.</summary>
    void Log(string message);

    /// <summary>
    /// Adds a file format to File ▸ Open: <paramref name="read"/> turns the file into a drawing (which replaces the
    /// open one, like opening a .cb file). Built-in formats (.cb, .dxf, .stl) keep their own readers.
    /// </summary>
    void AddImporter(FileFormat format, Func<string, CadDocument> read);

    /// <summary>Adds a file format to File ▸ Export: <paramref name="write"/> saves the drawing to the given path.</summary>
    void AddExporter(FileFormat format, Action<CadDocument, string> write);

    /// <summary>
    /// Adds a post processor macro: post processor templates can use {$name} or {$name(arguments)}. Built-in macros and
    /// a post processor's own macros take precedence, so use a name with the vendor as prefix ("acme.serial").
    /// </summary>
    void AddPostMacro(string name, Func<PostMacroContext, string> evaluate);

    /// <summary>
    /// Adds a drawing object type whose geometry is computed from parameters (<typeparamref name="TEntity"/> derives
    /// from <see cref="ParametricEntity"/>). Its parameters show in the property grid; drawings store its outlines as
    /// polylines too, so the object stays visible without the plugin (and in CamBam). Create objects with a command
    /// (<see cref="ICommandContext.AddEntities"/>).
    /// </summary>
    void AddEntityType<TEntity>() where TEntity : ParametricEntity, new();
}

/// <summary>A file type: its name in file dialogs and its extensions (".xyz").</summary>
public sealed record FileFormat(string Name, params string[] Extensions);

/// <summary>What a post processor macro of a plugin sees.</summary>
public sealed record PostMacroContext(CadDocument Document, MachineOp? Operation, string? Arguments);

/// <summary>A menu command of a plugin.</summary>
public sealed class PluginCommand
{
    /// <summary>Menu entry text; an underscore marks the access key ("_Gear...").</summary>
    public required string Header { get; init; }

    /// <summary>Top-level menu the command is added to: "Plugins" (default), "Draw", "Edit" or "Machining".</summary>
    public string Menu { get; init; } = "Plugins";

    /// <summary>Optional tooltip.</summary>
    public string? Description { get; init; }

    /// <summary>When true the command is only run with selected drawing objects (otherwise BamCam asks to select some).</summary>
    public bool RequiresSelection { get; init; }

    /// <summary>
    /// Optional toolbar button: the icon as SVG path data in a 24 x 24 box, drawn as lines, e.g.
    /// "M4,20 L12,4 L20,20 Z". Commands with an icon also get a button in the toolbar (tooltip: header and description).
    /// </summary>
    public string? Icon { get; init; }

    /// <summary>
    /// Optional: commands of the plugin with the same group name share one toolbar button with a small arrow, which
    /// opens a menu of them (as the align button does). The button shows the icon of the first command of the group
    /// that has one; commands of the group without an icon are in the menu too.
    /// </summary>
    public string? ToolbarGroup { get; init; }

    /// <summary>The action. Changes to the drawing must go through <see cref="ICommandContext.Change"/> to be undoable.</summary>
    public required Func<ICommandContext, Task> Execute { get; init; }
}

/// <summary>What a running command can see and do.</summary>
public interface ICommandContext
{
    /// <summary>The open drawing.</summary>
    CadDocument Document { get; }

    /// <summary>Selected drawing objects.</summary>
    IReadOnlyList<Entity> Selection { get; }

    /// <summary>Runs <paramref name="change"/> as one undoable step named <paramref name="description"/> and refreshes the view.</summary>
    void Change(string description, Action change);

    /// <summary>Adds objects to the active layer as one undoable step and selects them.</summary>
    void AddEntities(string description, IEnumerable<Entity> entities);

    /// <summary>Replaces the selection.</summary>
    void Select(IEnumerable<Entity> entities);

    /// <summary>Writes a line to the message window.</summary>
    void Log(string message);

    /// <summary>Asks for a number; null when cancelled.</summary>
    Task<double?> AskNumber(string title, string label, double defaultValue);

    /// <summary>Asks for a text; null when cancelled.</summary>
    Task<string?> AskText(string title, string label, string defaultValue = "");

    /// <summary>
    /// The G-code of the whole drawing as text, with the post processor of the drawing: toolpaths are generated when
    /// needed, warnings go to the message window. No file is written and no post-build command runs, so that nothing
    /// is sent to a machine. Null when there is nothing to post (or in a host that does not offer this).
    /// </summary>
    Task<string?> PostGCode() => Task.FromResult<string?>(null);

    /// <summary>
    /// Starts an interactive tool in the drawing (picking points with the mouse). The command returns at once; the
    /// tool runs until it calls <see cref="IToolContext.End"/> or the user presses Esc.
    /// </summary>
    void StartTool(PluginTool tool);
}

/// <summary>Modifier keys held during a click.</summary>
[Flags]
public enum ToolModifiers { None = 0, Shift = 1, Control = 2, Alt = 4 }

/// <summary>
/// Interactive drawing tool of a plugin (like BamCam's own drawing commands). Points are in drawing coordinates and
/// already snapped (grid and object snap as switched on by the user). Override what the tool needs.
/// </summary>
public abstract class PluginTool
{
    /// <summary>Text of the prompt bar while the tool runs (update with <see cref="IToolContext.SetPrompt"/>).</summary>
    public virtual string Prompt => "";

    /// <summary>The tool was started.</summary>
    public virtual void Started(IToolContext context) { }

    /// <summary>The mouse moved; redraw follows, so <see cref="Preview"/> can show a rubber band.</summary>
    public virtual void Moved(IToolContext context, Point2 point) { }

    /// <summary>Left click.</summary>
    public virtual void Clicked(IToolContext context, Point2 point, ToolModifiers modifiers) { }

    /// <summary>Enter or a middle click: by default the tool ends.</summary>
    public virtual void Finished(IToolContext context) => context.End();

    /// <summary>
    /// A key was pressed: "A" … "Z", "0" … "9", "Back", "Delete", "Space", "Tab", "Up", "Down", "Left", "Right",
    /// "Escape". Return true when the tool used it. An unused Escape ends the tool.
    /// </summary>
    public virtual bool KeyPressed(IToolContext context, string key) => false;

    /// <summary>Paths drawn as dashed preview (drawing coordinates), e.g. the figure up to the cursor.</summary>
    public virtual IEnumerable<Path2> Preview(IToolContext context) => [];

    /// <summary>The tool ended (by <see cref="IToolContext.End"/>, Esc or another command).</summary>
    public virtual void Ended(IToolContext context) { }
}

/// <summary>What a running plugin tool can see and do: everything of a command plus prompt, picking and ending.</summary>
public interface IToolContext : ICommandContext
{
    /// <summary>The last (snapped) cursor position.</summary>
    Point2 Cursor { get; }

    /// <summary>Size of one screen pixel in drawing units (for pick distances and marker sizes).</summary>
    double PixelSize { get; }

    /// <summary>Drawing objects at a point (within a few pixels), nearest first.</summary>
    IReadOnlyList<Entity> PickAt(Point2 point);

    void SetPrompt(string text);

    /// <summary>Redraws the drawing (and the preview).</summary>
    void Redraw();

    /// <summary>Ends the tool and returns to selection.</summary>
    void End();
}
