using BamCam.Core.Geometry;

namespace BamCam.Core.Cam;

public enum MoveKind { Rapid, Feed, ArcCW, ArcCCW, Dwell, Comment, DrillCycle }

/// <summary>Canned drilling cycle parameters (G81/G82/G83).</summary>
public readonly record struct DrillCycle(double RetractZ, double Peck, double Dwell);

/// <summary>
/// One machine move. For arcs, <see cref="Center"/> is the arc centre (absolute XY) and the
/// move ends at <see cref="To"/>; Z may change linearly (helix). For drill cycles, <see cref="To"/>
/// is the hole bottom.
/// </summary>
public readonly record struct Move(MoveKind Kind, Point3 To, double Feed = 0, Point2 Center = default,
    string? Text = null, double Seconds = 0, DrillCycle Cycle = default)
{
    public static Move Rapid(Point3 to) => new(MoveKind.Rapid, to);
    public static Move Line(Point3 to, double feed) => new(MoveKind.Feed, to, feed);
    public static Move Arc(Point3 to, Point2 center, bool clockwise, double feed) =>
        new(clockwise ? MoveKind.ArcCW : MoveKind.ArcCCW, to, feed, center);
    public static Move Note(string text) => new(MoveKind.Comment, default, Text: text);
    public static Move Drill(Point3 bottom, double feed, DrillCycle cycle) =>
        new(MoveKind.DrillCycle, bottom, feed, Cycle: cycle);

    public bool IsArc => Kind is MoveKind.ArcCW or MoveKind.ArcCCW;
    public bool IsMotion => Kind is MoveKind.Rapid or MoveKind.Feed or MoveKind.ArcCW or MoveKind.ArcCCW;
}

/// <summary>One continuous cut of a toolpath (with the rapids leading to it), see <see cref="Toolpath.Paths"/>.</summary>
public sealed class ToolpathPath
{
    /// <summary>Position within its toolpath (0-based).</summary>
    public int Index { get; init; }

    /// <summary>Depth level of the cut (lowest horizontal cutting Z).</summary>
    public double Z { get; set; } = double.PositiveInfinity;

    internal bool HasLevel { get; set; }

    public List<(Point3 From, Point3 To, MoveKind Kind)> Segments { get; } = [];
}

/// <summary>Moves generated by one machining operation (already ordered, ready to post).</summary>
public sealed class Toolpath
{
    public List<Move> Moves { get; } = [];

    /// <summary>Cut outlines at the final depth, for display of cut widths (optional).</summary>
    public List<Path2> CutWidthOutlines { get; } = [];

    public Point3? StartPosition { get; set; }

    public List<string> Warnings { get; } = [];

    /// <summary>Holding tabs applied by the generator (profiles only), for display and editing.</summary>
    public List<HoldingTab> TabPlacements { get; } = [];

    public void Add(Move m) => Moves.Add(m);

    /// <summary>
    /// Splits the display segments into separate paths in execution order, as stepped through by the
    /// toolpath view filter. A new path starts at each rapid-to-cut transition and wherever the cut
    /// goes below the depth level of the current path (the next Z level of a depth-first profile).
    /// Rapids belong to the path they lead to.
    /// </summary>
    public List<ToolpathPath> Paths(double tolerance = 0.01)
    {
        var result = new List<ToolpathPath>();
        var segments = DisplaySegments(tolerance).ToList();
        // Rapids that stay at or below the highest cutting Z (e.g. hops over holding tabs) don't end a path.
        var maxCutZ = segments.Where(s => s.Kind != MoveKind.Rapid).Select(s => Math.Max(s.From.Z, s.To.Z)).DefaultIfEmpty(0).Max();
        ToolpathPath? current = null;
        var pendingRapids = new List<(Point3, Point3, MoveKind)>();
        var lastWasRapid = true;
        foreach (var seg in segments)
        {
            var (from, to, kind) = seg;
            if (kind == MoveKind.Rapid)
            {
                pendingRapids.Add(seg);
                if (Math.Max(from.Z, to.Z) > maxCutZ + 1e-6) lastWasRapid = true;
                continue;
            }
            var horizontal = Math.Abs(to.Z - from.Z) < 1e-6;
            var deeper = current is { HasLevel: true } && to.Z < current.Z - 1e-6;
            if (current == null || lastWasRapid || deeper)
            {
                current = new ToolpathPath { Index = result.Count };
                result.Add(current);
            }
            current.Segments.AddRange(pendingRapids);
            pendingRapids.Clear();
            current.Segments.Add(seg);
            if (horizontal) current.Z = current.HasLevel ? Math.Min(current.Z, to.Z) : to.Z;
            else if (!current.HasLevel) current.Z = Math.Min(current.Z, to.Z);
            current.HasLevel |= horizontal;
            lastWasRapid = false;
        }
        if (current != null) current.Segments.AddRange(pendingRapids);
        foreach (var p in result)
            if (!p.HasLevel) p.Z = p.Segments.Where(s => s.Kind != MoveKind.Rapid).Select(s => Math.Min(s.From.Z, s.To.Z)).DefaultIfEmpty(0).Min();
        return result;
    }

    /// <summary>
    /// Removes final rapid moves that only lift the tool: the post processor retracts at the start of
    /// the next operation and in the file footer, which mirrors CamBam's output.
    /// </summary>
    public void TrimTrailingRetracts()
    {
        while (Moves.Count >= 2 && Moves[^1].Kind == MoveKind.Rapid)
        {
            var prev = Moves[^2];
            if (!prev.IsMotion || !prev.To.XY.AlmostEquals(Moves[^1].To.XY, 1e-9) || Moves[^1].To.Z < prev.To.Z) break;
            Moves.RemoveAt(Moves.Count - 1);
        }
    }

    /// <summary>Last commanded position, if any motion exists.</summary>
    public Point3? LastPosition
    {
        get
        {
            for (var i = Moves.Count - 1; i >= 0; i--)
                if (Moves[i].IsMotion) return Moves[i].To;
            return StartPosition;
        }
    }

    public BoundingBox Bounds()
    {
        var b = BoundingBox.Empty;
        foreach (var m in Moves)
            if (m.IsMotion) b = b.Include(m.To);
        return b;
    }

    /// <summary>Approximate machining time in seconds (rapids at <paramref name="rapidRate"/> units/min).</summary>
    public double EstimateSeconds(double rapidRate = 5000)
    {
        var pos = StartPosition ?? Point3.Zero;
        double t = 0;
        foreach (var m in Moves)
        {
            if (!m.IsMotion)
            {
                t += m.Seconds;
                continue;
            }
            var len = MoveLength(pos, m);
            var rate = m.Kind == MoveKind.Rapid ? rapidRate : Math.Max(m.Feed, 1e-6);
            t += len / rate * 60;
            pos = m.To;
        }
        return t;
    }

    public static double MoveLength(Point3 from, Move m)
    {
        if (!m.IsArc) return Point3.Distance(from, m.To);
        var r = Point2.Distance(from.XY, m.Center);
        var a0 = (from.XY - m.Center).Angle;
        var a1 = (m.To.XY - m.Center).Angle;
        var sweep = m.Kind == MoveKind.ArcCCW ? Angles.Normalize(a1 - a0) : Angles.Normalize(a0 - a1);
        if (sweep < Tolerance.Epsilon) sweep = Angles.TwoPi;
        var xy = sweep * r;
        var dz = m.To.Z - from.Z;
        return Math.Sqrt(xy * xy + dz * dz);
    }

    /// <summary>Points along the path for display (arcs flattened).</summary>
    public IEnumerable<(Point3 From, Point3 To, MoveKind Kind)> DisplaySegments(double tolerance = 0.01)
    {
        Point3? pos = StartPosition;
        foreach (var m in Moves)
        {
            if (m.Kind == MoveKind.DrillCycle)
            {
                var top = m.To with { Z = m.Cycle.RetractZ };
                if (pos is { } p0) yield return (p0, top with { Z = p0.Z }, MoveKind.Rapid);
                var start = pos is { } p1 ? top with { Z = p1.Z } : top;
                if (start.Z > top.Z) yield return (start, top, MoveKind.Rapid);
                yield return (top, m.To, MoveKind.Feed);
                yield return (m.To, start, MoveKind.Rapid);
                pos = start;
                continue;
            }
            if (!m.IsMotion) continue;
            if (pos is null)
            {
                pos = m.To;
                continue;
            }
            var from = pos.Value;
            if (!m.IsArc)
            {
                yield return (from, m.To, m.Kind);
            }
            else
            {
                var r = Point2.Distance(from.XY, m.Center);
                var a0 = (from.XY - m.Center).Angle;
                var a1 = (m.To.XY - m.Center).Angle;
                var ccw = m.Kind == MoveKind.ArcCCW;
                var sweep = ccw ? Angles.Normalize(a1 - a0) : -Angles.Normalize(a0 - a1);
                if (Math.Abs(sweep) < Tolerance.Epsilon) sweep = ccw ? Angles.TwoPi : -Angles.TwoPi;
                var arc = new Arc2(m.Center, r, a0, sweep);
                var n = arc.SegmentCount(tolerance);
                var prev = from;
                for (var i = 1; i <= n; i++)
                {
                    var t = (double)i / n;
                    var p = arc.PointAt(t).ToPoint3(from.Z + (m.To.Z - from.Z) * t);
                    yield return (prev, p, m.Kind);
                    prev = p;
                }
            }
            pos = m.To;
        }
    }
}
