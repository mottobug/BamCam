using BamCam.Core.Geometry;

namespace BamCam.Core.Cam;

public enum MoveKind { Rapid, Feed, ArcCW, ArcCCW, Dwell, Comment }

/// <summary>
/// One machine move. For arcs, <see cref="Center"/> is the arc centre (absolute XY) and the
/// move ends at <see cref="To"/>; Z may change linearly (helix).
/// </summary>
public readonly record struct Move(MoveKind Kind, Point3 To, double Feed = 0, Point2 Center = default, string? Text = null, double Seconds = 0)
{
    public static Move Rapid(Point3 to) => new(MoveKind.Rapid, to);
    public static Move Line(Point3 to, double feed) => new(MoveKind.Feed, to, feed);
    public static Move Arc(Point3 to, Point2 center, bool clockwise, double feed) =>
        new(clockwise ? MoveKind.ArcCW : MoveKind.ArcCCW, to, feed, center);
    public static Move Note(string text) => new(MoveKind.Comment, default, Text: text);

    public bool IsArc => Kind is MoveKind.ArcCW or MoveKind.ArcCCW;
    public bool IsMotion => Kind is MoveKind.Rapid or MoveKind.Feed or MoveKind.ArcCW or MoveKind.ArcCCW;
}

/// <summary>Moves generated by one machining operation (already ordered, ready to post).</summary>
public sealed class Toolpath
{
    public List<Move> Moves { get; } = [];

    /// <summary>Cut outlines at the final depth, for display of cut widths (optional).</summary>
    public List<Path2> CutWidthOutlines { get; } = [];

    public Point3? StartPosition { get; set; }

    public List<string> Warnings { get; } = [];

    public void Add(Move m) => Moves.Add(m);

    /// <summary>Last commanded position, if any motion exists.</summary>
    public Point3? LastPosition
    {
        get
        {
            for (var i = Moves.Count - 1; i >= 0; i--)
                if (Moves[i].IsMotion) return Moves[i].To;
            return StartPosition;
        }
    }

    public BoundingBox Bounds()
    {
        var b = BoundingBox.Empty;
        foreach (var m in Moves)
            if (m.IsMotion) b = b.Include(m.To);
        return b;
    }

    /// <summary>Approximate machining time in seconds (rapids at <paramref name="rapidRate"/> units/min).</summary>
    public double EstimateSeconds(double rapidRate = 5000)
    {
        var pos = StartPosition ?? Point3.Zero;
        double t = 0;
        foreach (var m in Moves)
        {
            if (!m.IsMotion)
            {
                t += m.Seconds;
                continue;
            }
            var len = MoveLength(pos, m);
            var rate = m.Kind == MoveKind.Rapid ? rapidRate : Math.Max(m.Feed, 1e-6);
            t += len / rate * 60;
            pos = m.To;
        }
        return t;
    }

    public static double MoveLength(Point3 from, Move m)
    {
        if (!m.IsArc) return Point3.Distance(from, m.To);
        var r = Point2.Distance(from.XY, m.Center);
        var a0 = (from.XY - m.Center).Angle;
        var a1 = (m.To.XY - m.Center).Angle;
        var sweep = m.Kind == MoveKind.ArcCCW ? Angles.Normalize(a1 - a0) : Angles.Normalize(a0 - a1);
        if (sweep < Tolerance.Epsilon) sweep = Angles.TwoPi;
        var xy = sweep * r;
        var dz = m.To.Z - from.Z;
        return Math.Sqrt(xy * xy + dz * dz);
    }

    /// <summary>Points along the path for display (arcs flattened).</summary>
    public IEnumerable<(Point3 From, Point3 To, MoveKind Kind)> DisplaySegments(double tolerance = 0.01)
    {
        Point3? pos = StartPosition;
        foreach (var m in Moves)
        {
            if (!m.IsMotion) continue;
            if (pos is null)
            {
                pos = m.To;
                continue;
            }
            var from = pos.Value;
            if (!m.IsArc)
            {
                yield return (from, m.To, m.Kind);
            }
            else
            {
                var r = Point2.Distance(from.XY, m.Center);
                var a0 = (from.XY - m.Center).Angle;
                var a1 = (m.To.XY - m.Center).Angle;
                var ccw = m.Kind == MoveKind.ArcCCW;
                var sweep = ccw ? Angles.Normalize(a1 - a0) : -Angles.Normalize(a0 - a1);
                if (Math.Abs(sweep) < Tolerance.Epsilon) sweep = ccw ? Angles.TwoPi : -Angles.TwoPi;
                var arc = new Arc2(m.Center, r, a0, sweep);
                var n = arc.SegmentCount(tolerance);
                var prev = from;
                for (var i = 1; i <= n; i++)
                {
                    var t = (double)i / n;
                    var p = arc.PointAt(t).ToPoint3(from.Z + (m.To.Z - from.Z) * t);
                    yield return (prev, p, m.Kind);
                    prev = p;
                }
            }
            pos = m.To;
        }
    }
}
